export const CATALOGUES: Record<Locale, Catalogue> = { 'zh-HK': zhTraditional, 'zh-TW': zhTraditional, 'zh-CN': zhCN, en };
export const KEYS = Object.keys(en) as Key[];

/** Plain-text interpolation. Messages are sent without a parse mode, so no escaping is needed. */
export function t(locale: Locale, key: Key, params: Record<string, string | number> = {}): string {
  return CATALOGUES[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}
export function isKey(x: string): x is Key {
  return x in en;
}
